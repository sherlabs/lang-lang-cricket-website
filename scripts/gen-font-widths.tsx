// Dev tool: measures each bundled OG face's glyph advances with real satori and writes lib/social/font-widths.ts.
// `pnpm tsx --conditions=react-server scripts/gen-font-widths.tsx`. Re-run when a face is added; tests/social-font-widths.test.ts validates the result.
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { ImageResponse } from 'next/og'
import sharp from 'sharp'
import { FONT_MENU, OG_BODY_FACES } from '../lib/theme/fonts'

const N = 16
const PX = 100
const faces: { key: string; file: string; weight: 400 | 500 | 600 | 700 }[] = [
  ...Object.entries(FONT_MENU).map(([key, m]) => { const f = m.faces.find((x) => x.weight === m.ogWeight)!; return { key, file: f.ttf, weight: f.weight } }),
  ...OG_BODY_FACES.map((f) => ({ key: `inter-${f.weight}`, file: f.ttf, weight: f.weight })),
]

async function ink(font: ArrayBuffer, weight: 400 | 500 | 600 | 700, text: string): Promise<number> {
  const el = (
    <div style={{ display: 'flex', width: 2800, height: 160, background: '#fff', color: '#000', fontFamily: 'F', fontSize: PX, whiteSpace: 'pre', alignItems: 'center' }}>{text}</div>
  )
  const png = Buffer.from(await new ImageResponse(el, { width: 2800, height: 160, fonts: [{ name: 'F', data: font, weight, style: 'normal' }] }).arrayBuffer())
  const { data, info } = await sharp(png).greyscale().raw().toBuffer({ resolveWithObject: true })
  let min = info.width, max = 0
  for (let y = 0; y < info.height; y++) for (let x = 0; x < info.width; x++) if (data[y * info.width + x] < 128) { if (x < min) min = x; if (x > max) max = x }
  return max - min + 1
}

const out: Record<string, number[]> = {}
for (const f of faces) {
  const buf = readFileSync(path.resolve(f.file))
  const font = buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength) as ArrayBuffer
  const base = await ink(font, f.weight, '||')
  const widths: number[] = []
  for (let c = 32; c <= 126; c++) {
    const w = await ink(font, f.weight, `|${String.fromCharCode(c).repeat(N)}|`)
    widths.push(Math.max(0, Math.round(((w - base) / N / PX) * 1000) / 1000))
  }
  out[f.key] = widths
  console.log(f.key, 'avg', (widths.reduce((a, b) => a + b, 0) / widths.length).toFixed(3))
}
writeFileSync('lib/social/font-widths.ts', `// Generated by scripts/gen-font-widths.tsx (do not edit). Glyph advance in em, ASCII 32 to 126, measured with satori for each bundled OG face.\nexport const FONT_WIDTHS: Record<string, readonly number[]> = ${JSON.stringify(out)}\n`)
